import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'

const root = new URL('../../assets/embedded/', import.meta.url)
const manifest = JSON.parse(await readFile(new URL('source-manifest.json', root), 'utf8'))
for (const file of manifest.files) {
  const bytes = await readFile(new URL(file.path, root))
  if (createHash('sha256').update(bytes).digest('hex') !== file.sha256) {
    throw new Error(`Imported reader asset changed without updating provenance: ${file.path}`)
  }
}
const text = async path => readFile(new URL(path, root), 'utf8')
const assets = {
  template: await text('html/webview-template.html'),
  errorTemplate: await text('html/error.html'),
  resetCss: await text('css/reset.css'),
  articleCss: await text('css/article.css'),
  markCss: await text('css/mark.css'),
  bottomLineCss: await text('css/bottom-line.css'),
  bridgeJs: await text('js/webview-bridge.js'),
  nativeHostJs: await text('js/react-native-host.js'),
  errorImageBase64: (await readFile(new URL('image/error.png', root))).toString('base64'),
}
const output = '// Generated by src/reader/generate-assets.mjs. Edit the source assets, then regenerate.\n' +
  '// Imported assets retain their source license and notices; see assets/embedded/SOURCE-LICENSE.txt.\n' +
  `export const readerAssets = ${JSON.stringify(assets, null, 2)} as const\n`
const target = new URL('./embedded.generated.ts', import.meta.url)
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Reader embedding is stale; run generate-assets.mjs')
} else {
  await writeFile(target, output)
}
