import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import ts from 'typescript';

const read = relative => readFile(new URL(relative, import.meta.url));
const digest = data => createHash('sha256').update(data).digest('hex');
const manifest = JSON.parse(await read('./manifest.json'));
assert.equal(manifest.synthetic, true);
assert.equal(manifest.nativeExecution, 'pending-adapter-and-device');
for (const file of manifest.files) {
  assert(/^(scenarios\.json|documents\.ts|resources\.ts|articles\/[a-z-]+\.html)$/.test(file.path), 'Fixture manifest must remain scoped');
  assert.equal(digest(await read('./' + file.path)), file.sha256, file.path);
}
const bundle = JSON.parse(await read('./scenarios.json'));
const compiledExport = async file => {const exports = {}; vm.runInNewContext(ts.transpileModule(String(await read(file)), {compilerOptions: {module: ts.ModuleKind.CommonJS}}).outputText, {exports}); return exports;};
const documents = (await compiledExport('./documents.ts')).fixtureDocuments;
for (const [path, html] of Object.entries(documents)) assert.equal(html, String(await read('./' + path)), 'Metro document exports must retain the exact pinned HTML bytes');
const artwork = (await compiledExport('./resources.ts')).fixtureArtworkBase64;
assert.equal(digest(Buffer.from(artwork, 'base64')), digest(await read('../assets/drawable/ic_app_logo.png')), 'Fixture artwork must retain the copied source asset bytes');
assert.equal(Object.keys(bundle.scenarios).length, manifest.scenarioCount);
const ids = Object.values(bundle.ids);
assert(ids.every(id => /^[a-f0-9]{8}-[a-f0-9]{4}-4[a-f0-9]{3}-8[a-f0-9]{3}-[a-f0-9]{12}$/.test(id)));
assert.equal(new Set(ids).size, ids.length);
const kotlinHash = text => [...text].reduce((value, char) => (Math.imul(value, 31) + char.charCodeAt(0)) | 0, 0);
assert.equal(new Set(ids.map(kotlinHash)).size, ids.length, 'Fixture UUIDs must not collide as legacy Kotlin mark identifiers');
const mixed = String(await read('./articles/mixed.html'));
assert(mixed.includes('id="first">Alpha <strong>bold</strong> end.') && mixed.includes('id="second">Second paragraph with quote.'));
const requiredRich = ['<img', '<ul', '<ol', '<blockquote', '<pre', '<table', 'class="katex"', '<details', 'id="outline"', 'id="last-heading"'];
assert(requiredRich.every(fragment => mixed.includes(fragment)));
const base = bundle.scenarios['reader-mixed'].payload;
assert(base.database.sr_bookmark_comment.some(mark => mark.is_deleted === 1));
assert(base.database.sr_bookmark_comment.some(mark => mark.type === 3 && JSON.parse(mark.metadata).parent_id === bundle.ids['deleted-root']));
assert(base.database.sr_bookmark_comment.some(mark => JSON.parse(mark.source).some(path => path.type === 'image')));
assert(base.database.sr_bookmark_comment.some(mark => JSON.parse(mark.source).length === 0 && JSON.parse(mark.approx_source).exact));
assert(base.database.ps_data_local__local_bookmark_info.some(row => row.id === `collection-${bundle.ids.owner}-${bundle.ids.mixed}`));
for (const scenario of Object.values(bundle.scenarios)) {
  assert.equal(scenario.nativeExecution, 'pending-adapter-and-device');
  for (const article of scenario.payload.cache) assert(manifest.files.some(file => file.path === article.htmlFile));
  for (const route of scenario.payload.api) assert(route.path.startsWith('/v1/') && !route.path.includes('..'));
}
const code = ts.transpileModule(String(await read('./transport.ts')), {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022}}).outputText;
const abortExports = await compiledExport('../src/utils/abort.ts');
const exports = {};
vm.runInNewContext(code, {exports, URL, Response, AbortController, ReadableStream, TextEncoder, TextDecoder, setTimeout, clearTimeout, require(path) {assert.equal(path, '../src/utils/abort'); return abortExports;}});
const fetch = exports.createFixtureFetch(base);
let response = await fetch(bundle.apiOrigin + '/v1/rss/entries?limit=20&cursor=fixture-page-2');
assert.equal((await response.json()).data.items[0].id, 'rss-entry-history', 'Cursor responses must take precedence over the generic first page');
response = await fetch(bundle.apiOrigin + '/v1/bookmark/content', {method: 'POST', body: JSON.stringify({bookmark_uid: bundle.ids.video})});
assert((await response.text()).includes('data-cues='));
const errors = exports.createFixtureFetch(bundle.scenarios['feedback-error'].payload);
response = await errors(bundle.apiOrigin + '/v1/user/report', {method: 'POST', body: '{}'});
assert.equal(response.status, 400, 'Prepared error overrides must be deterministic');
response = await exports.createFixtureFetch(bundle.scenarios['reader-load-error'].payload)(bundle.apiOrigin + '/v1/bookmark/content', {method: 'POST', body: JSON.stringify({bookmark_uid: bundle.ids.mixed})});
assert.equal(response.status, 503, 'Error overrides must preserve request body specificity');
assert.equal((await response.json()).data, 'source_unavailable', 'Original ErrorResponse expects nullable text in canonical503 data');
const streaming = exports.createFixtureFetch(bundle.scenarios['reader-ai-stream'].payload);
response = await streaming(bundle.apiOrigin + '/v1/bookmark/overview', {method: 'POST', body: '{}'});
const reader = response.body.getReader();
let chunk = await reader.read();
assert(new TextDecoder().decode(chunk.value).includes('A deterministic '));
assert(!new TextDecoder().decode(chunk.value).includes('done'), 'First native capture must observe an intermediate stream state');
let collected = new TextDecoder().decode(chunk.value);
while (!(chunk = await reader.read()).done) collected += new TextDecoder().decode(chunk.value);
assert(collected.includes('streamed summary.') && collected.includes('"done":true'));
const streamController = new AbortController();
response = await streaming(bundle.apiOrigin + '/v1/bookmark/outline', {method: 'POST', body: '{}', signal: streamController.signal});
const abortedReader = response.body.getReader(); await abortedReader.read(); streamController.abort();
await assert.rejects(() => abortedReader.read(), 'An aborted native fixture stream must reject its next read');
await assert.rejects(() => fetch('https://example.com/v1/rss/entries'), /external origin/);
await assert.rejects(() => fetch(bundle.apiOrigin + '/v1/unprepared'), /No prepared fixture response/);
await assert.rejects(() => exports.createFixtureFetch(bundle.scenarios['offline-cached'].payload)(bundle.apiOrigin + '/v1/rss/entries'), /offline/);
const controller = new AbortController(); controller.abort();
await assert.rejects(() => fetch(bundle.apiOrigin + '/v1/rss/entries', {signal: controller.signal}));
console.log(JSON.stringify({syntheticScenarios: manifest.scenarioCount, pinnedDocuments: manifest.files.filter(file => file.path.endsWith('.html')).length, richContentInputs: requiredRich.length, nativeExecution: 'pending-adapter-and-device'}, null, 2));
