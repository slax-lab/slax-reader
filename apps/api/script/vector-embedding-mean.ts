import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { format, resolveConfig } from 'prettier'
import { normalized, VECTOR_DIMENSIONS, VECTOR_MODEL } from '../src/utils/vectorEmbedding'

function parseOptions(args: string[]): { input: string; source: string } {
  const options = new Map<string, string>()
  for (let index = 0; index < args.length; index++) {
    const key = args[index]
    if (!['--input', '--source'].includes(key)) throw new Error('unknown_option')
    if (options.has(key)) throw new Error('duplicate_option')
    const value = args[++index]
    if (!value?.trim() || value.startsWith('--')) throw new Error('missing_option_value')
    options.set(key, value)
  }
  const input = options.get('--input')
  const source = options.get('--source')
  if (!input || !source) throw new Error('missing_required_option')
  return { input, source }
}

async function main() {
  const options = parseOptions(process.argv.slice(2))
  const input: unknown = JSON.parse(await readFile(resolve(options.input), 'utf8'))
  if (!input || typeof input !== 'object') throw new Error('invalid_vector_input')
  const vectors: unknown[] = Array.isArray(input) ? input : Object.values(input)
  if (!vectors.length) throw new Error('empty_vector_input')
  const sum = new Float64Array(VECTOR_DIMENSIONS)
  for (const vector of vectors) {
    if (!Array.isArray(vector) || vector.length !== VECTOR_DIMENSIONS || vector.some(value => typeof value !== 'number' || !Number.isFinite(value)))
      throw new Error('invalid_vector_input')
    const unit = normalized(vector)
    for (let index = 0; index < sum.length; index++) sum[index] += unit[index]
  }
  const values = Array.from(sum, value => value / vectors.length)
  const version = createHash('sha256').update(JSON.stringify(values)).digest('hex').slice(0, 12)
  const metadata = { version, model: VECTOR_MODEL, dimensions: VECTOR_DIMENSIONS, sampleSize: vectors.length, source: options.source, generatedAt: new Date().toISOString() }
  const output = fileURLToPath(new URL('../src/utils/embeddingMean.ts', import.meta.url))
  const contents = `// Generated by script/vector-embedding-mean.ts. Do not edit.
export const EMBEDDING_MEAN = {
  version: ${JSON.stringify(version)},
  model: ${JSON.stringify(VECTOR_MODEL)},
  dimensions: ${VECTOR_DIMENSIONS},
  sampleSize: ${vectors.length},
  source: ${JSON.stringify(options.source)},
  generatedAt: ${JSON.stringify(metadata.generatedAt)},
  values: ${JSON.stringify(values)}
} as const
`
  await writeFile(output, await format(contents, { ...(await resolveConfig(output)), filepath: output }))
  console.log(JSON.stringify({ ...metadata, output }))
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch(error => {
    const reason = error instanceof Error && /^[a-z_]{1,100}$/.test(error.message) ? error.message : 'vector_mean_failed'
    console.error(JSON.stringify({ error: reason }))
    process.exitCode = 1
  })
}
